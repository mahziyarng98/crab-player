#!/usr/bin/env python3
"""Generate src/player/mpv_shim.rs from the libmpv2-sys bindings.

Every `mpv_*` function declared by libmpv2-sys gets a `#[no_mangle]`
forwarder that resolves the real symbol with dlsym on first use. With these
definitions in the binary the linker satisfies every libmpv reference
locally and `--as-needed` drops `libmpv.so.2` from DT_NEEDED, so a missing
libmpv becomes an error the player reports instead of a loader failure.

Usage: scripts/gen-mpv-shim.py [path/to/libmpv2-sys/pregenerated_bindings.rs]
Without an argument the bindings are looked up in ~/.cargo/registry for the
libmpv2-sys version in Cargo.lock.
"""

import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def bindings_path():
    if len(sys.argv) > 1:
        return sys.argv[1], "(given path)"
    lock = open(os.path.join(ROOT, "Cargo.lock"), encoding="utf-8").read()
    version = re.search(r'name = "libmpv2-sys"\nversion = "([^"]+)"', lock).group(1)
    cargo_home = os.environ.get("CARGO_HOME", os.path.expanduser("~/.cargo"))
    hits = glob.glob(
        f"{cargo_home}/registry/src/*/libmpv2-sys-{version}/pregenerated_bindings.rs"
    )
    if not hits:
        sys.exit(f"libmpv2-sys {version} not found in {cargo_home}; run `cargo fetch` first")
    return hits[0], version


def main():
    path, version = bindings_path()
    text = open(path, encoding="utf-8").read()
    # Declarations look like `pub fn name(args) -> ret;`, possibly over
    # several lines, inside `unsafe extern "C" { ... }` blocks.
    decls = re.findall(r"pub fn (mpv_\w+)\((.*?)\)(\s*->\s*[^;]+)?;", text, re.S)
    out = [
        "// @generated by scripts/gen-mpv-shim.py from the libmpv2-sys "
        f"{version} bindings. Do not edit.",
        "//",
        "// One forwarder per libmpv function; see `mpv_dl` for why.",
        "",
        "use super::mpv_dl::Slot;",
        "#[allow(unused_imports)]",
        "use libmpv2_sys::*;",
        "",
    ]
    for name, args, ret in decls:
        args = " ".join(args.split()).rstrip(",")
        ret = " ".join((ret or "").split())
        params = [a.split(":", 1) for a in args.split(", ") if a] if args else []
        names = ", ".join(p[0].strip() for p in params)
        types = ", ".join(p[1].strip() for p in params)
        out += [
            "#[unsafe(no_mangle)]",
            f"unsafe extern \"C\" fn {name}({args}){(' ' + ret) if ret else ''} {{",
            f"    static SLOT: Slot = Slot::new(c\"{name}\");",
            f"    type F = unsafe extern \"C\" fn({types}){(' ' + ret) if ret else ''};",
            "    // SAFETY: the symbol comes from libmpv, whose C declaration is the",
            "    // one libmpv2-sys was generated from; the caller upholds the",
            "    // function's own contract.",
            f"    unsafe {{ std::mem::transmute::<*mut std::ffi::c_void, F>(SLOT.get())({names}) }}",
            "}",
            "",
        ]
    target = os.path.join(ROOT, "src", "player", "mpv_shim.rs")
    open(target, "w", encoding="utf-8").write("\n".join(out))
    # Formatted like the rest of the tree, so `cargo fmt` leaves it alone.
    subprocess.run(["rustfmt", "--edition", "2024", target], check=True)
    print(f"{len(decls)} forwarders written to {os.path.relpath(target, ROOT)}")


if __name__ == "__main__":
    main()
